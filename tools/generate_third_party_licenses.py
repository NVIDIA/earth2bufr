"""Generate THIRD_PARTY_LICENSES.txt for the Rust crates compiled into the extension.

The crate set is the transitive closure of normal (non-dev, non-build) dependencies
of the root package, as pinned by ``Cargo.lock``. For every crate the script copies
the license and NOTICE files shipped in the crate itself, so per-crate copyright
lines and Apache-2.0 NOTICE text are preserved. Identical texts are grouped.

Usage::

    python tools/generate_third_party_licenses.py          # (re)write the file
    python tools/generate_third_party_licenses.py --check  # fail if it is stale

Requires ``cargo`` and a populated cargo registry (run ``cargo fetch --locked``).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES.txt"
LICENSE_RE = re.compile(r"^(LICEN[CS]E|COPYING|UNLICENSE)", re.IGNORECASE)
NOTICE_RE = re.compile(r"^NOTICE", re.IGNORECASE)
RULE = "=" * 80

HEADER = """\
Third-Party Licenses: Rust Dependencies
=======================================

The earth2bufr extension module is compiled from Rust and statically links the
crates listed below (including transitive dependencies), as pinned by Cargo.lock.
Each crate is distributed under the license(s) shown; the license and NOTICE
texts that the crates themselves ship follow.

This file is generated by tools/generate_third_party_licenses.py. Do not edit it
by hand.
"""


def _cargo_metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--manifest-path", str(ROOT / "Cargo.toml")],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(out.stdout)


def _runtime_crates(meta: dict) -> list[dict]:
    """Return packages reachable from the root through normal dependency edges."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    stack = [root]
    while stack:
        pkg_id = stack.pop()
        if pkg_id in seen:
            continue
        seen.add(pkg_id)
        for dep in nodes[pkg_id]["deps"]:
            if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    seen.discard(root)
    return sorted((packages[i] for i in seen), key=lambda p: (p["name"], p["version"]))


def _read_texts(crate: dict, pattern: re.Pattern[str]) -> list[tuple[str, str]]:
    crate_dir = Path(crate["manifest_path"]).parent
    found = []
    for path in sorted(crate_dir.iterdir()):
        if path.is_file() and pattern.match(path.name):
            text = path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            if text:
                found.append((path.name, text))
    return found


def _section(title: str, crates: list[str], text: str) -> str:
    users = "\n".join(f"  - {c}" for c in crates)
    return f"{RULE}\n{title}\n{RULE}\n\nApplies to:\n{users}\n\n{text}\n"


def render() -> str:
    """Return the full text of THIRD_PARTY_LICENSES.txt."""
    crates = _runtime_crates(_cargo_metadata())
    licenses: dict[str, list[str]] = defaultdict(list)
    notices: dict[str, list[str]] = defaultdict(list)
    summary = []
    unshipped = []
    for crate in crates:
        label = f"{crate['name']} {crate['version']}"
        summary.append(f"  {label}: {crate['license'] or 'UNKNOWN'}")
        lic = _read_texts(crate, LICENSE_RE)
        if not lic:
            unshipped.append(crate)
        for _, text in lic:
            licenses[text].append(label)
        for _, text in _read_texts(crate, NOTICE_RE):
            notices[text].append(label)

    # Some crates publish no license file. Where they offer Apache-2.0 as an option, elect it and
    # attach the canonical Apache-2.0 text, citing the upstream repository.
    elected: dict[str, list[str]] = defaultdict(list)
    if unshipped:
        apache = max(
            (t for t in licenses if "Apache License" in t and "Version 2.0" in t), key=lambda t: len(licenses[t])
        )
        for crate in unshipped:
            if "Apache-2.0" not in (crate["license"] or ""):
                sys.exit(f"error: {crate['name']} ships no license file and does not offer Apache-2.0")
            repo = crate["repository"] or "no repository listed"
            elected[f"{crate['name']} {crate['version']} ({repo}); declared: {crate['license']}"] = []
        licenses[apache].extend(f"{c['name']} {c['version']}" for c in unshipped)

    parts = [HEADER, f"Crates ({len(crates)})\n----------\n" + "\n".join(summary) + "\n"]
    parts.append("\nLICENSE TEXTS\n-------------\n")
    for i, (text, users) in enumerate(sorted(licenses.items(), key=lambda kv: kv[1][0]), 1):
        parts.append(_section(f"License text {i} of {len(licenses)}", users, text))
    if notices:
        parts.append("\nNOTICES\n-------\n")
        for i, (text, users) in enumerate(sorted(notices.items(), key=lambda kv: kv[1][0]), 1):
            parts.append(_section(f"Notice {i} of {len(notices)}", users, text))
    if elected:
        parts.append(
            "\nCRATES WITHOUT A PUBLISHED LICENSE FILE\n----------------------------------------\n\n"
            "The following crates do not include a license file in their published package. Each declares\n"
            "Apache-2.0 as one of its license options, and Apache-2.0 is the option used here. The\n"
            "Apache-2.0 text above is listed under these crates. Copyright remains with the authors named\n"
            "in the upstream repository.\n\n" + "\n".join(f"  - {k}" for k in elected) + "\n"
        )
    return "\n".join(parts).rstrip() + "\n"


def main() -> int:
    """Write the file, or verify it with ``--check``."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit non-zero if the file is out of date")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"{OUTPUT.name} is out of date; run tools/generate_third_party_licenses.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
